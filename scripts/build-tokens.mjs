#!/usr/bin/env node
// Write src/styles/tokens.css from src/styles/tokens.ts (VIS-02). Run after any change to tokens.ts:
//   node scripts/build-tokens.mjs          write the file
//   node scripts/build-tokens.mjs --check  exit 1 if the committed file differs (test/tokens.test.mjs does the same)
// Node strips the TypeScript types itself (22.18+), so this needs no build step and no dependency.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const out = fileURLToPath(new URL('src/styles/tokens.css', root));

export function renderTokensCss(vars) {
  const lines = vars.map(([name, value]) => `  ${name}: ${value};`);
  return [
    '/* GENERATED by scripts/build-tokens.mjs from src/styles/tokens.ts: edit that file, then run the script. */',
    '/* Colours, font roles, type roles, grid and the default (light) section theme. Guide: docs/design-tokens.md */',
    ':root {',
    ...lines,
    '}',
    '',
  ].join('\n');
}

// Run as a script (the test imports renderTokensCss only).
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { cssVariables } = await import(new URL('src/styles/tokens.ts', root).href);
  const css = renderTokensCss(cssVariables());
  if (process.argv.includes('--check')) {
    const current = readFileSync(out, 'utf8');
    if (current !== css) {
      console.error('src/styles/tokens.css is out of date: run node scripts/build-tokens.mjs');
      process.exit(1);
    }
  } else {
    writeFileSync(out, css);
    process.stdout.write(`wrote ${out} (${cssVariables().length} custom properties)\n`);
  }
}
